public class Predict {
    public static void main(String[] args){
        // 7 / 2 gives 3
        // 7%2 gives 1
        // 7.0/2 gives 3.5
        // (int)(7.0/2) gives 3

        System.out.println(7 / 2);
        System.out.println(7 % 2);
        System.out.println(7.0 / 2);
        System.out.println((int)(7.0 / 2));
    }
}
